export interface InstitutionalStudent {
  id: string;
  studentId: string;
  fullName: string;
  email: string;
  batch: 'B1' | 'B2';
  semester: string;
  course: string;
  department: string;
  attendancePct: number;
  classesPresent: number;
  classesTotal: number;
  marksAverage: number;
  cia1Score: number;
  quiz1Score: number;
  assignment1Score: number;
  labCompletedCount: number;
  labTotalCount: number;
  riskLevel: 'critical' | 'high' | 'medium' | 'safe';
  riskScore: number;
  riskFactors: string[];
  recommendedInterventions: string[];
  phone?: string;
  avatarLetter: string;
}

export interface TeacherSession {
  id: string;
  subjectCode: string;
  subjectName: string;
  section: string;
  date: string;
  timeSlot: string;
  topic: string;
  totalStudents: number;
  presentCount: number;
  absentCount: number;
  lateCount: number;
  attendancePct: number;
  status: 'closed' | 'open';
  records: Record<string, 'present' | 'absent' | 'late'>;
}

export interface InstitutionalAssessment {
  id: string;
  subjectCode: string;
  subjectName: string;
  section: string;
  title: string;
  type: 'cia' | 'quiz' | 'assignment' | 'practical' | 'mid_sem' | 'end_sem';
  maxMarks: number;
  weightage: string;
  date: string;
  topic: string;
  isPublished: boolean;
  averageScore?: number;
  marks: Record<string, { marks: number; grade: string; remarks?: string }>;
}

export interface InstitutionalLabExperiment {
  id: string;
  expNumber: number;
  title: string;
  subjectCode: string;
  subjectName: string;
  section: string;
  maxMarks: number;
  dueDate: string;
  submissions: Record<string, {
    status: 'verified' | 'submitted' | 'incomplete' | 'pending';
    marks?: number;
    verifiedAt?: string;
    remarks?: string;
  }>;
}

